import { expect, test } from "@playwright/test";
import { expectAccessible, signInAs } from "./support";
test("policy studio projects canonical rows as a read-only tree and outline", async ({ page }) => {
  await signInAs(page, "agent_architect", "/studio/policies?template=kyc&tab=tree");
  const viewer = page.getByRole("region", { name: "Policy tree viewer", exact: true });
  await expect(viewer).toBeVisible();
  await expect(viewer.getByLabel("Policy source", { exact: true })).toHaveValue("policy.yaml");
  await viewer.getByRole("button", { name: /^screening-ready/ }).click();
  await viewer.getByRole("radio", { name: "Outline", exact: true }).click();
  await viewer.getByRole("region", { name: "Policy outline", exact: true }).getByRole("button", { name: /reference.*screening-ready.yaml/ }).click();
  await viewer.getByRole("button", { name: "Follow decision table", exact: true }).click();
  await viewer.getByRole("radio", { name: "Tree", exact: true }).click();
  await viewer.getByLabel("Policy source", { exact: true }).selectOption({ label: "table.kyc.screening-ready.v1" });
  await viewer.getByRole("button", { name: /1\. SR-001/ }).click();
  await expect(viewer).toContainText("The first matching row wins");
  await viewer.getByRole("radio", { name: "Outline", exact: true }).click();
  const outline = viewer.getByRole("region", { name: "Policy outline", exact: true });
  await expect(outline).toContainText("evaluation = ERROR");
  await outline.getByRole("button", { name: /condition.*evaluation = ERROR/ }).click();
  await expect(viewer.getByRole("region", { name: "Policy node details" })).toContainText("evaluationStatus");
  await expectAccessible(page);
  await viewer.getByRole("button", { name: "Open source", exact: true }).click();
  await expect(page).toHaveURL(/tab=advanced/);
  await expect(page.getByLabel("catalog/decision-tables/screening-ready.yaml", { exact: true })).toContainText("SR-001");
});
test("policy owners read the installation policy as plain rules and its open requirements", async ({ page }) => {
  await signInAs(page, "agent_architect", "/studio/policies");
  await expect(page.getByLabel("Policy", { exact: true })).toHaveValue("kyc-agentic");
  await expect(page.getByRole("tab", { name: /Rules/ })).toHaveAttribute("aria-selected", "true");
  const intake = page.getByRole("list", { name: "Intake ready rules" });
  // The SYNTHETIC checkpoint rules: intake is ready with a relationship and completed agent tasks.
  await expect(intake.getByRole("listitem").first()).toContainText("Relationship has at least 1 entries");
  await expect(intake.getByRole("listitem").first()).toContainText("SYNTHETIC_INTAKE_READY");
  await expect(page.getByRole("heading", { name: "Test the policy (what-if)" })).toBeVisible();
  const matrix = page.getByRole("table", { name: "Base level by party type and product" });
  await expect(matrix.getByLabel("Individual with deposit", { exact: true })).toHaveValue("SDD");
  await expect(matrix.getByRole("row", { name: /Individual/ })).toContainText("applied as CDD");
  const overlays = page.getByRole("list", { name: "Risk overlays" });
  await expect(overlays.getByRole("switch", { name: "Politically exposed person enabled" })).toHaveAttribute("aria-checked", "true");
  await expect(overlays.getByRole("switch", { name: "Confirmed adverse media enabled" })).toHaveAttribute("aria-checked", "false");
  await page.getByLabel("Policy set", { exact: true }).selectOption({ label: "GB · individual · card, deposit, payments" });
  await expect(overlays.getByRole("listitem").filter({ hasText: "Politically exposed person" })).toContainText("Required by pack");
  await expect(overlays.getByRole("switch", { name: "Politically exposed person enabled" })).toBeDisabled();
  await page.getByLabel("Policy set", { exact: true }).selectOption({ label: "US · individual · card, deposit, payments" });
  await page.getByRole("radio", { name: "Flow", exact: true }).click();
  await expect(page.getByRole("region", { name: "Policy tree viewer", exact: true })).toBeVisible();
  await page.getByRole("tab", { name: "Requirements" }).click();
  await expect(page.getByRole("heading", { name: "US · individual · card, deposit, payments" })).toBeVisible();
  const content = page.getByRole("table", { name: "Installation policy content fields" });
  // EDD triggers combine the SYNTHETIC placeholders with what the diligence design derives; provider permission stays open.
  await expect(content.getByRole("row").filter({ hasText: "EDD triggers" })).toContainText("Resolved");
  await expect(content.getByRole("row").filter({ hasText: "Permitted providers" })).toContainText("Unresolved");
  await expect(content.getByRole("row").filter({ hasText: "Screening threshold" })).toContainText("Resolved");
  await expect(page.getByRole("heading", { name: "Requirements by diligence level" })).toBeVisible();
  await page.getByLabel("Policy set", { exact: true }).selectOption({ label: "GB · individual · card, deposit, payments" });
  await expect(page.getByRole("heading", { name: "GB · individual · card, deposit, payments" })).toBeVisible();
  await expect(page).toHaveURL(/set=policy\.pack\.gb/);
  await expectAccessible(page);
  await page.screenshot({ path: test.info().outputPath("policy-studio-requirements.png"), fullPage: true });
});
test("analysts can inspect policy trees from the catalog on mobile", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await signInAs(page, "cdd_analyst", "/catalogs/policies?selected=table.kyc.screening-ready.v1");
  const inspector = page.getByRole("dialog", { name: "Policy details", exact: true });
  await inspector.getByRole("radio", { name: "Policy tree", exact: true }).click();
  await expect(inspector.getByRole("region", { name: "Policy outline", exact: true })).toContainText("SR-001");
  await expect(inspector.getByText("Read only", { exact: true })).toBeVisible();
  await expectAccessible(page);
});
