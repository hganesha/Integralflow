import { readFile } from "node:fs/promises";
import { resolve } from "node:path";

export async function loadAuthoringTemplates(domainsPath: string) {
  const templates = [
    { id: "kyc-agentic", name: "Agentic KYC: individual onboarding", directory: "kyc-agentic", dependencies: ["policy.yaml"] },
    { id: "kyb-agentic", name: "Agentic KYB: business onboarding", directory: "kyb-agentic", dependencies: ["policy.yaml"] },
    { id: "kyc-edd-agentic", name: "Agentic KYC (EDD): individual onboarding", directory: "kyc-edd-agentic", dependencies: ["policy.yaml"] },
    { id: "kyb-edd-agentic", name: "Agentic KYB (EDD): business onboarding", directory: "kyb-edd-agentic", dependencies: ["policy.yaml"] },
    { id: "kyb-sdd-agentic", name: "Agentic KYB (SDD): business onboarding", directory: "kyb-sdd-agentic", dependencies: ["policy.yaml"] },
    { id: "securities-agentic", name: "Agentic onboarding: institutional securities client", directory: "securities-agentic", dependencies: ["policy.yaml"] },
    // Archived deterministic flows (domains/archive/README.md): kept as a frozen regression baseline
    // and parity oracle for the agentic flows; listed so their sources stay inspectable, not as a
    // starting point for new work. Generated by scripts/sync-kyc-package.mjs and
    // scripts/sync-kyb-package.mjs; sources, vendored manifests and policy binding are compile dependencies.
    { id: "kyc", name: "KYC v2 (archived, deterministic)", directory: "archive/kyc-v2-deterministic", dependencies: ["README.md", "policy-binding.yaml", "library/skills.json", "source/kyc-workflow.json"] },
    { id: "kyb", name: "KYB synthetic (archived, deterministic)", directory: "archive/kyb-deterministic", dependencies: ["README.md", "library/policy.synthetic-neutral.json", "library/skills.json", "library/synthetic-kyb.json", "source/kyb-workflow.json"] },
    // Production slice 1 (scripts/sync-kyb-screening-package.mjs): its topology, candidate policy
    // and vendored manifests are compile dependencies.
    { id: "kyb-screening", name: "KYB screening and ownership (slice 1)", directory: "kyb-screening", dependencies: ["README.md", "library/skills.json", "policy/slice-policy.json", "source/workflow.json"] },
  ];
  return Promise.all(templates.map(async ({ id, name, directory, dependencies }) => {
    const [packageSource, workflowSource, files] = await Promise.all([
      readFile(resolve(domainsPath, directory, "package.yaml"), "utf8"),
      readFile(resolve(domainsPath, directory, "workflow.yaml"), "utf8"),
      Promise.all(dependencies.map(async (path) => [path, await readFile(resolve(domainsPath, directory, path), "utf8")] as const)),
    ]);
    return { id, name, packageSource, workflowSource, sourceFiles: Object.fromEntries(files) };
  }));
}
