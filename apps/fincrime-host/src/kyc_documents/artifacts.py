"""Reproducible, portable exports; shared by the CLI and repository build check."""
from __future__ import annotations

import json
from pathlib import Path

from . import CATALOG_VERSION
from .fields import FIELDS, SECTIONS
from .model import fingerprint
from .profiles import ENTITY_PACKS, PROFILES, REVIEW_EVENTS
from .runtime import audit_catalog, contract, coverage_report, extraction_schema, object_definitions

# Exact inspected repository revision, retained for reproducible design provenance.
DOCUBRICKS_COMMIT = "3de54e97437d284ea898a2e0e4367efd1ba97851"


def json_text(value):
    return json.dumps(value, sort_keys=True, indent=2, ensure_ascii=False, allow_nan=False) + "\n"


def render_bundle():
    audit = audit_catalog()
    outputs = {}
    entries = []
    for profile in sorted(PROFILES.values(), key=lambda p: p.id):
        compiled = contract(profile.id)
        prefix = profile.id + "/"
        outputs[prefix + "fields.json"] = json_text(compiled["profile"])
        outputs[prefix + "extraction.schema.json"] = json_text(extraction_schema(profile.id))
        outputs[prefix + "instructions.md"] = compiled["instructions"]
        entries.append({**profile.model_dump(mode="json"), "contract_hash": compiled["contract_hash"],
                        "fields_path": prefix + "fields.json", "schema_path": prefix + "extraction.schema.json",
                        "instructions_path": prefix + "instructions.md"})
    catalog = {
        "api_version": "kyc.documents/v1alpha1", "version": CATALOG_VERSION,
        "maturity": "draft_field_contract", "jurisdiction_baseline": "neutral_with_explicit_document_specific_variants",
        "source_document_universe": "conversation:kyc-document-universe-2026-11-07",
        "design_reference": {"repository": "https://github.com/hganesha/DocuBricks", "revision": DOCUBRICKS_COMMIT,
            "files": ["docs/schema-authoring.md", "docs/schema-architecture-v2.md", "Schemas/fs/kyc_cdd_form/fields.json",
                      "Schemas/fs/trust_account_opening_package/fields.json", "Schemas/fs/merchant_onboarding_application/fields.json"]},
        "qualification": {"real_document_evaluations": 0, "confidence_calibration": "not_performed",
            "ocr_or_model_implementation": "external_provider_required", "production_qualified": False,
            "existing_skill_binding": "field_contract_sidecar_not_automatically_dispatched"},
        "statistics": audit, "document_types": entries,
    }
    catalog["catalog_hash"] = fingerprint(catalog)
    outputs["catalog.json"] = json_text(catalog)
    outputs["field-library.json"] = json_text({"version": CATALOG_VERSION,
        "sections": SECTIONS, "fields": [f.model_dump(mode="json") for f in FIELDS.values()], "$defs": object_definitions()})
    outputs["coverage.json"] = json_text(coverage_report())
    outputs["entity-packages.json"] = json_text({"selection_semantics": "candidate_evidence_options_not_mandatory_checklists",
        "packages": ENTITY_PACKS})
    outputs["review-events.json"] = json_text({"selection_semantics": "candidate_refresh_options_selected_by_admitted_policy",
        "events": REVIEW_EVENTS})
    return outputs


def render_index():
    lines = ["# KYC document field catalog", "", "Generated by `scripts/build_document_catalog.py`; edit the authored Python definitions, not this index.", "",
        "Per-type `fields.json`, `extraction.schema.json` and `instructions.md` are generated, not committed: run `kyc-documents show <id>`, `kyc-documents schema <id>`, or `python scripts/build_document_catalog.py --export <dir>` for the full bundle.", "",
        "All entries are draft extraction contracts. Key fields identify important evidence to review; they do not establish legal collection requirements.", "",
        "| Document type | Key fields | Total fields | Contract |", "| --- | --- | ---: | --- |"]
    for profile in sorted(PROFILES.values(), key=lambda p: (p.family, p.id)):
        fields = ", ".join("`" + f + "`" for f in profile.key_fields)
        lines.append(f"| {profile.display_name} (`{profile.id}`) | {fields} | {len(profile.field_names)} | `kyc-documents show {profile.id}` |")
    return "\n".join(lines) + "\n"


def write_bundle(output: Path):
    rendered = render_bundle()
    for relative, text in rendered.items():
        path = output / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    return {"output": str(output), "artifacts": len(rendered), "document_types": len(PROFILES)}
