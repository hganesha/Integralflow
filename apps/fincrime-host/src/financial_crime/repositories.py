"""Storage contracts: implementations may use SQL, document or service backends."""
from contextlib import AbstractContextManager
from dataclasses import dataclass
from typing import Any, Protocol

from .contracts import Record, Ref


@dataclass(frozen=True)
class JobEntry:
    tenant: str
    actor: str
    key: str
    request_hash: str
    body: dict


@dataclass(frozen=True)
class OutboxEntry:
    tenant: str
    id: str
    hash: str
    status: str
    command: dict
    receipt: dict | None


class Repository(Protocol):
    def transaction(self) -> AbstractContextManager: ...
    def put(self, record: Record) -> Ref: ...
    def records(self, tenant: str, object_type: str) -> list[Record]: ...
    def state(self, tenant: str, kind: str, object_id: str) -> tuple[int, dict | None]: ...
    def set_state(self, tenant: str, kind: str, object_id: str, expected_revision: int, data: dict) -> int: ...
    def event(self, tenant: str, event: dict) -> None: ...
    def events(self, tenant: str) -> list[dict]: ...
    def audit_chain(self, tenant: str) -> list[tuple[dict, str]]: ...
    def get_job(self, tenant: str, actor: str, key: str) -> JobEntry | None: ...
    def jobs(self, tenant: str, *, actor: str | None = None, request_hash: str | None = None) -> list[JobEntry]: ...
    def claim_job(self, tenant: str, actor: str, key: str, request_hash: str, body: dict, *, resume: bool = False) -> None: ...
    def save_job(self, tenant: str, actor: str, key: str, body: dict) -> None: ...
    def discard_job(self, tenant: str, actor: str, key: str) -> None: ...
    def add_outbox(self, tenant: str, command: dict) -> None: ...
    def outbox_item(self, tenant: str, object_id: str) -> OutboxEntry | None: ...
    def pending_outbox(self, tenant: str, limit: int = 100) -> list[OutboxEntry]: ...
    def set_outbox_status(self, tenant: str, object_id: str, status: str, receipt: dict | None = None, *, expected: str | None = None) -> None: ...

