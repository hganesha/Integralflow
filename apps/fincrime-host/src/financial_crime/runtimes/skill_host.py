"""skill.execution.v1 host for the library (EHF docs/implementation/skill-library-integration-contract.md).

EHF's capability gateway runs a library skill by calling this host:

    GET  /healthz                                   liveness, unauthenticated
    GET  /v1/bundle                                 the bundle lock the platform pinned
    POST /v1/skills/{skill_id}/executions           run one skill (synchronously; 200 with a terminal response)
    GET  /v1/skills/executions/{execution_id}       the execution's response; 404 when unknown (e.g. after a restart)
    POST /v1/skills/executions/{execution_id}/cancel

The host owns no data and no authority. Everything a skill reads arrives in the request: canonical
records in the context sections and the pinned policy in the `policy` section, scoped to exactly
those records. A skill's provider calls go back to the platform gateway with the request's delegated
envelope, and only to capabilities the request permits. What the skill returns is a computation.
The platform validates and commits it, never this host.

The bundle lock (`resources/bundle.lock.json`) is generated by EHF from this catalog with the
platform's own rule (scripts/sync-library-bundle-lock.mjs). The host refuses to start when the lock
does not match the installed catalog, and refuses a request for any other bundle or skill version.

EHF extension skills (docs/skill-extensions.md) may return `proposed_records` in their payload
(skill.execution.v1 §6.2 shape). The host lifts them into the computation's `proposed_records`
unchanged, and the platform validates and commits them like any host's proposals.
"""
