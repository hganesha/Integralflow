class EnvelopeVerifier:
    """Verifies the delegated envelope's RS256 signature with the platform's envelope public key.

    The gateway verifies every callback it receives, so a forged envelope can never spend authority
    there. Verifying here as well refuses an execution whose envelope the platform did not sign
    before any skill code runs. Only a public key can be held here: the shared development HMAC
    secret would let the host mint envelopes, so without a public key the host decodes the claims
    unverified, which ``SECURITY_PROFILE=production`` refuses.
    """

    def __init__(self, public_key_pem: str | None):
        self.public_key = public_key_pem.strip() if public_key_pem and public_key_pem.strip() else None

    @classmethod
    def from_env(cls, env=os.environ) -> "EnvelopeVerifier":
        verifier = cls(env.get("SKILL_HOST_ENVELOPE_PUBLIC_KEY_PEM"))
        if verifier.public_key is None and env.get("SECURITY_PROFILE", "development") == "production":
            raise SystemExit("SKILL_HOST_ENVELOPE_PUBLIC_KEY_PEM is required under SECURITY_PROFILE=production")
        return verifier

    def claims(self, token: str) -> dict | None:
        if self.public_key is None:
            return _jwt_claims(token)
        import jwt  # PyJWT, with cryptography for RS256 (requirements-runtime.lock)
        try:
            value = jwt.decode(token, self.public_key, algorithms=["RS256"], options={"require": ["exp"], "verify_aud": False})
        except jwt.PyJWTError:
            return None
        return value if isinstance(value, dict) else None


class ExecutionStore:
    """Completed executions by id with the request digest they answer, so a retry of the same request
    returns the same response and a status poll after a restart still finds it.

    In memory by default; ``SKILL_HOST_EXECUTIONS_DB`` (a sqlite file on a mounted volume) keeps them
    across restarts. Responses carry computations and limitations, never context content.
    """

    def __init__(self, path: str | None = None):
        self.memory: dict[str, tuple[str, dict]] = {}
        self.path = path
        if path:
            import sqlite3
            self.db = sqlite3.connect(path, check_same_thread=False, isolation_level=None)
            self.db.execute("pragma journal_mode=wal")
            self.db.execute("create table if not exists executions (execution_id text primary key, request_digest text not null, response text not null)")

    def get(self, execution_id: str) -> tuple[str, dict] | None:
        if not self.path:
            return self.memory.get(execution_id)
        row = self.db.execute("select request_digest, response from executions where execution_id = ?", (execution_id,)).fetchone()
        return (row[0], json.loads(row[1])) if row else None

    def put_once(self, execution_id: str, request_digest: str, response: dict) -> tuple[str, dict]:
        """Store a response unless one exists; return the stored one (the first answer wins)."""
        if not self.path:
            return self.memory.setdefault(execution_id, (request_digest, response))
        self.db.execute("insert or ignore into executions(execution_id, request_digest, response) values (?, ?, ?)",
                        (execution_id, request_digest, json.dumps(response, sort_keys=True)))
        return self.get(execution_id)  # type: ignore[return-value]


def _jwt_claims(token: str) -> dict | None:
    """The delegated envelope's claims, unverified (development only; see EnvelopeVerifier)."""
    parts = token.split(".")
    if len(parts) != 3:
        return None
    try:
        value = json.loads(base64.urlsafe_b64decode(parts[1] + "=" * (-len(parts[1]) % 4)))
    except (ValueError, json.JSONDecodeError):
        return None
    return value if isinstance(value, dict) else None


def _section_case(provenance_ref: str) -> str | None:
    match = re.match(r"^case:([^@/]+)", provenance_ref)
    return match.group(1) if match else None


def _time(value: str | None, fallback: datetime) -> datetime:
    if not value:
        return fallback
    parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    return parsed if parsed.tzinfo else parsed.replace(tzinfo=timezone.utc)


def load_lock() -> dict:
    """The generated bundle lock, checked against the installed catalog and code."""
    from ..registry import bundle_code_hash, instructions_for
    lock = json.loads(files("financial_crime").joinpath("resources", "bundle.lock.json").read_text())
    catalog = json.loads(files("financial_crime").joinpath("resources", "catalog.json").read_text())
    if lock.get("bundle_digest") != "sha256:" + catalog["bundle_code_hash"] or catalog["bundle_code_hash"] != bundle_code_hash():
        raise SystemExit("bundle.lock.json does not match the installed catalog or code; regenerate it (scripts/sync-library-bundle-lock.mjs)")
    manifests = {(m["id"], m["semver"]): m for m in catalog["skills"]}
    registry = load_registry()
    for entry in lock["skills"]:
        manifest = manifests.get((entry["id"], entry["version"]))
        if not manifest or entry["code_digest"] != "sha256:" + manifest["code_hash"] or entry["instructions_digest"] != "sha256:" + manifest["instruction_hash"]:
            raise SystemExit(f"bundle.lock.json entry {entry['id']}@{entry['version']} does not match the catalog")
        spec = registry.get(entry["id"])
        if spec is None or any(manifest.get(key) != value for key, value in spec.manifest().items()):
            raise SystemExit(f"runtime manifest differs from released catalog: {entry['id']}")
        try:
            instructions_for(entry["id"])
        except SkillError as error:
            raise SystemExit(f"bundle instructions failed integrity: {entry['id']}") from error
    return lock


class GatewayProvider:
    """A library Provider that calls one platform capability through the gateway."""
    provider_id = GATEWAY_PROVIDER

    def __init__(self, execution: "Execution", capability_id: str, evidence: list[Ref]):
        self.execution, self.capability_id, self.evidence = execution, capability_id, evidence

    async def invoke(self, capability: str, request: dict) -> ProviderResponse:
        output = await self.execution.call_gateway(self.capability_id, request)
        # The gateway's receipt is the provenance of this call; the library's evidence binding is
        # the admitted context the request was built from (the sections this execution received).
        return ProviderResponse(provider_id=GATEWAY_PROVIDER, capability=capability, request_hash=digest(request), payload=output,
                                evidence_refs=self.evidence, source_version="ehf-gateway", coverage={"complete": True}, synthetic=self.execution.synthetic)


class Execution:
    def __init__(self, host: "SkillHost", request: dict, traceparent: str | None):
        self.host, self.request, self.traceparent = host, request, traceparent
        self.capability_calls = 0
        self.receipts: list[str] = []
        self.synthetic = True

    async def call_gateway(self, capability_id: str, request: dict) -> dict:
        callback, limits = self.request["callback"], self.request["limits"]
        if self.capability_calls >= limits["max_capability_calls"]:
            raise SkillError("CONTROL_FAILED", "capability call budget exhausted")
        self.capability_calls += 1
        headers = {"content-type": "application/json", "x-execution-envelope": callback["delegated_envelope"]}
        gateway_token = self.host.gateway_token()
        if gateway_token:
            headers["authorization"] = f"Bearer {gateway_token}"
        if self.traceparent:
            headers["traceparent"] = self.traceparent
        body = {"invocationId": f"{self.request['execution_id']}:call-{self.capability_calls}", "capabilityId": capability_id, "effect": "read", "input": request}
        try:
            async with httpx.AsyncClient(timeout=30, follow_redirects=False, transport=self.host.transport) as client:
                response = await client.post(callback["gateway_url"].rstrip("/") + "/v1/invoke", headers=headers, json=body)
        except httpx.HTTPError:
            raise SkillError("SOURCE_UNAVAILABLE", "gateway unreachable", Status.NEEDS_EVIDENCE, True) from None
        try:
            result = response.json()
        except ValueError:
            result = None
        if response.status_code == 403:
            raise SkillError("ACCESS_DENIED", "gateway denied the capability")
        if not response.is_success or not isinstance(result, dict):
            raise SkillError("SOURCE_UNAVAILABLE", f"gateway answered {response.status_code}", Status.NEEDS_EVIDENCE, True)
        if isinstance(result.get("receiptDigest"), str):
            self.receipts.append(result["receiptDigest"])
        if result.get("status") != "succeeded" or not isinstance(result.get("output"), dict):
            raise SkillError("SOURCE_UNAVAILABLE", "the capability established nothing", Status.NEEDS_EVIDENCE)
        return result["output"]


class SkillHost:
    """
    Inbound, only the capability gateway may call the host; outbound, the host presents its own
    identity to the gateway. Both follow the platform's WORKLOAD_AUTH mechanism
    (workload_identity.py): a development shared token, or verified workload-identity tokens.
    """

    def __init__(self, token: str | None = None, *, gateway_token: str | Callable[[], str | None] | None = None,
                 verifier: CallerVerifier | None = None, transport: Any = None, lock: dict | None = None,
                 envelopes: EnvelopeVerifier | None = None, executions: ExecutionStore | None = None):
        if verifier is None:
            if not token or len(token) < 16:
                raise SystemExit("SKILL_HOST_AUTH_TOKEN must be at least 16 characters")
            verifier = CallerVerifier({GATEWAY_CALLER: "SKILL_HOST_AUTH_TOKEN"}, {"SKILL_HOST_AUTH_TOKEN": token})
        self.verifier, self.transport = verifier, transport
        self.gateway_token: Callable[[], str | None] = gateway_token if callable(gateway_token) else (lambda: gateway_token)
        self.lock = lock or load_lock()
        self.entries = {(e["id"], e["version"]): e for e in self.lock["skills"]}
        self.registry = load_registry()
        self.envelopes = envelopes or EnvelopeVerifier(None)
        self.executions = executions or ExecutionStore()
        self.guard = threading.Lock()

    def authorized(self, header: str | None) -> bool:
        return self.verifier.caller(header) == GATEWAY_CALLER

    def status(self, execution_id: str) -> dict | None:
        with self.guard:
            found = self.executions.get(execution_id)
        return found[1] if found else None

    def execute(self, skill_id: str, body: Any, idempotency_key: str | None, traceparent: str | None) -> dict:
        if not isinstance(body, dict) or body.get("contract_version") != CONTRACT_VERSION or body.get("skill_id") != skill_id:
            raise HostError(400, "INPUT_INVALID")
        for key in ("execution_id", "skill_version", "bundle_digest", "input", "context", "callback", "limits"):
            if key not in body:
                raise HostError(400, "INPUT_INVALID")
        if idempotency_key != body["execution_id"]:
            raise HostError(400, "INPUT_INVALID")
        body_digest = digest(body)
        with self.guard:
            existing = self.executions.get(body["execution_id"])
        if existing:
            if existing[0] != body_digest:
                raise HostError(409, "INPUT_INVALID")
            return existing[1]
        if skill_id not in self.registry:
            raise HostError(404, "INPUT_INVALID")
        entry = self.entries.get((skill_id, body["skill_version"]))
        # Exactly this version from exactly this bundle; never a nearby one.
        if not entry or body["bundle_digest"] != self.lock["bundle_digest"] or self.registry[skill_id].version != body["skill_version"]:
            raise HostError(409, "INTEGRITY_FAILURE")
        skill_input, context = body["input"], body["context"]
        envelope = context.get("envelope") or {}
        if envelope.get("tenant_id") != skill_input.get("tenant_id") or envelope.get("case_id") != skill_input.get("case_id"):
            raise HostError(403, "ACCESS_DENIED")
        for section in context.get("sections", []):
            case_id = _section_case(section.get("provenance_ref", ""))
            if case_id is not None and case_id != envelope.get("case_id"):
                raise HostError(403, "ACCESS_DENIED")
        claims = self.envelopes.claims(body["callback"].get("delegated_envelope", ""))
        now = time.time()
        if (not claims or claims.get("delegated_to") != f"skills:{skill_id}@{body['skill_version']}" or not isinstance(claims.get("exp"), (int, float))
                or claims["exp"] <= now or _time(body["callback"]["expires_at"], datetime.now(timezone.utc)).timestamp() <= now
                or (isinstance(claims.get("tenant_id"), str) and claims["tenant_id"] != skill_input.get("tenant_id"))):
            raise HostError(403, "ACCESS_DENIED")
        base = {"contract_version": CONTRACT_VERSION, "execution_id": body["execution_id"],
                "trace": {"instructions_digest": entry.get("instructions_digest"), "code_digest": entry.get("code_digest"), "subskill_executions": []}}
        if _time(body["limits"]["deadline_at"], datetime.now(timezone.utc)).timestamp() <= now:
            response = {**base, "lifecycle": "FAILED_EXECUTION", "computation": None, "error": {"code": "TIMEOUT", "retryable": True, "detail_ref": None}}
        else:
            started = time.monotonic()
            execution = Execution(self, body, traceparent)
            try:
                response = asyncio.run(self._run(skill_id, body, execution, base, started))
            except HostError:
                raise
            except Exception:
                response = {**base, "lifecycle": "FAILED_EXECUTION", "computation": None, "error": {"code": "CONTROL_FAILED", "retryable": False, "detail_ref": None}}
        with self.guard:
            return self.executions.put_once(body["execution_id"], body_digest, response)[1]

    async def _run(self, skill_id: str, body: dict, execution: Execution, base: dict, started: float) -> dict:
        spec = self.registry[skill_id]
        skill_input, context = body["input"], body["context"]
        tenant = skill_input["tenant_id"]
        as_of = _time(skill_input["as_of_time"], datetime.now(timezone.utc))
        records, policy = self._records(context, tenant, as_of)
        if policy is None:
            # No pinned policy, no authority: the host grants nothing by default. The platform
            # sends the case's pinned policy projection as the `policy` section, or does not call.
            metrics = {"duration_ms": int((time.monotonic() - started) * 1000), "capability_calls": 0, "model_calls": 0}
            return {**base, "lifecycle": "COMPLETED_EXECUTION", "error": None, "computation": {
                "business_status": "NEEDS_EVIDENCE", "payload": {}, "proposed_records": [], "negative_searches": [], "requested_effects": [],
                "unresolved_items": [{"code": "POLICY_UNRESOLVED", "subject_ref": "", "explanation": "no pinned policy section was sent"}],
                "metrics": metrics}}
        execution.synthetic = all(r.synthetic for r in records) if records else True
        permitted = set(body["callback"].get("permitted_capabilities", []))
        capabilities = {c for c in spec.capabilities if c in permitted or PLATFORM_CAPABILITIES.get(c) in permitted}
        # Authority comes only from the pinned policy: `skill:<id>` (and `effect:<mode>` for a
        # skill that writes) must be granted there; the request's own skill id grants nothing.
        permissions = {p for p in policy.get("permissions", []) if isinstance(p, str)}
        policy = {**policy, "permissions": sorted(permissions), "synthetic": execution.synthetic,
                  "permitted_providers": {c: [GATEWAY_PROVIDER] for c in capabilities}}
        policy.setdefault("version", "unversioned")
        policy.setdefault("jurisdiction", "unspecified")
        store = Store()
        store.put(Record(id=skill_input["policy_snapshot_ref"], tenant_id=tenant, object_type="Policy", data=policy,
                         observed_at=as_of, recorded_at=as_of, synthetic=execution.synthetic))
        for record in records:
            store.put(record)
        evidence = [r.ref() for r in records]
        router = Router({c: GatewayProvider(execution, c if c in permitted else PLATFORM_CAPABILITIES[c], evidence) for c in capabilities})
        purpose = skill_input["purpose"]
        profile = AgentProfile(id="ehf-skill-host", instructions="Run one pinned skill for the EHF platform.", allowed_skills={skill_id: spec.version},
                               permissions=permissions, purposes={purpose}, capabilities=capabilities,
                               timeout_seconds=max(1, min(300, _time(body["limits"]["deadline_at"], as_of).timestamp() - time.time())))
        classifications = {"internal"} | {r.classification for r in records}
        principal = Principal(tenant_id=tenant, actor_id=skill_input["actor_ref"], permissions=permissions | {"execution:recover"},
                              purposes={purpose}, classifications=classifications)
        from ..contracts import Invocation
        invocation = Invocation(execution_id=skill_input["execution_id"], skill_id=skill_id, skill_version=spec.version, tenant_id=tenant,
                                actor_ref=skill_input["actor_ref"], profile_id=profile.id, case_id=skill_input.get("case_id"), subject_ids=[],
                                object_refs=evidence, parameters=skill_input["parameters"], purpose=purpose,
                                policy_snapshot_ref=skill_input["policy_snapshot_ref"], as_of_time=as_of, knowledge_cutoff=as_of,
                                idempotency_key=skill_input["idempotency_key"], trace_id=skill_input["trace_id"])
        try:
            commands: list[dict] = []
            result = await Executor(store, [profile], router, command_sink=commands.extend).run(invocation, principal)
        finally:
            store.close()
        metrics = {"duration_ms": int((time.monotonic() - started) * 1000), "capability_calls": execution.capability_calls,
                   "model_calls": execution.capability_calls if spec.mode == "model" else 0}
        code = result.error.code if result.error else None
        if result.lifecycle == "FAILED" and code not in BUSINESS_GAPS:
            mapped = code if code in ERROR_CODES else "CONTROL_FAILED"
            return {**base, "lifecycle": "FAILED_EXECUTION", "computation": None,
                    "error": {"code": mapped, "retryable": mapped in TRANSIENT and bool(result.error and result.error.retryable), "detail_ref": None}}
        payload = dict(result.payload or {})
        proposed = []
        if "proposed_records" in spec.output.get("properties", {}):
            evidence = ([{"receipt_digest": r} for r in execution.receipts] or
                        [{"section_id": x["id"], "content_digest": x["content_digest"]} for x in context.get("sections", []) if x.get("kind") != "policy"])[:64]
            proposed = [{**item, "evidence": item.get("evidence") or evidence} for item in payload.pop("proposed_records", [])]
        unresolved = [{"code": u.code, "subject_ref": u.subject_ref or "", "explanation": u.explanation or u.code} for u in result.unresolved_items]
        if code in BUSINESS_GAPS:
            unresolved.append({"code": code, "subject_ref": "", "explanation": str(result.error.message or code)[:2000]})
        status = result.status.value
        # The executor applied (or held) the skill's effect commands against this request's
        # throwaway store; only what the platform can commit may leave as a result. A command with
        # no platform form blocks the node instead of reporting a success whose effect vanished.
        sections = [{"section_id": x["id"], "content_digest": x["content_digest"]} for x in context.get("sections", []) if x.get("kind") != "policy"][:64]
        for command in commands:
            forwarded = _forward_command(command)
            if forwarded is not None:
                proposed.append({**forwarded, "local_ref": f"effect:{len(proposed)}", "evidence": sections})
            else:
                status = "BLOCKED"
                unresolved.append({"code": "EFFECT_NOT_FORWARDED", "subject_ref": str(command.get("id") or ""),
                                   "explanation": f"{command.get('kind')}:{command.get('type')} has no platform case command; nothing was committed"})
        return {**base, "lifecycle": "COMPLETED_EXECUTION", "error": None, "computation": {
            "business_status": status, "payload": payload, "proposed_records": proposed, "unresolved_items": unresolved,
            "negative_searches": [], "requested_effects": [], "metrics": metrics}}

    def _records(self, context: dict, tenant: str, as_of: datetime) -> tuple[list[Record], dict | None]:
        records, policy = [], None
        for section in context.get("sections", []):
            value = section.get("value")
            if section.get("kind") == "policy" and section.get("id") == "policy" and isinstance(value, dict):
                policy = dict(value)
                continue
            if section.get("quarantined"):
                continue
            for item in value if isinstance(value, list) else []:
                if not (isinstance(item, dict) and isinstance(item.get("object_type"), str) and isinstance(item.get("object_id"), str)
                        and isinstance(item.get("data"), dict)):
                    continue
                observed = _time(item.get("observed_at"), as_of)
                records.append(Record(id=item["object_id"], tenant_id=tenant, object_type=item["object_type"], data=item["data"],
                                      version_id=str(item.get("version_id") or digest(item["data"])), subject_ids=list(item.get("subject_ids") or []),
                                      valid_from=_time(item["valid_from"], as_of) if item.get("valid_from") else None,
                                      valid_to=_time(item["valid_to"], as_of) if item.get("valid_to") else None,
                                      observed_at=min(observed, as_of), recorded_at=min(observed, as_of),
                                      classification=str(item.get("classification") or "internal"), synthetic=bool(item.get("synthetic", False))))
        return records, policy


def _forward_command(command: dict) -> dict | None:
    """The platform proposal for one library effect command, or None when it has none.

    A scheduled review becomes an analyst work item due at the scheduled time (an
    ``UnresolvedQuestion`` proposal, committed as ``ProposeWorkItem``); every other library
    state or outbox command has no platform form yet."""
    data = command.get("data") or {}
    if command.get("kind") == "state" and command.get("type") == "schedule" and isinstance(data.get("due_at"), str):
        action = str(data.get("action") or "review").upper()
        return {"record_type": "UnresolvedQuestion", "body": {
            "question": f"Scheduled {action.lower()} of this relationship is due.",
            "work_type": f"PERIODIC_{action}" if re.fullmatch(r"[A-Z][A-Z0-9_]{1,50}", action) else "PERIODIC_REVIEW",
            "due_at": data["due_at"]}}
    return None


def make_handler(host: SkillHost):
    class Handler(BaseHTTPRequestHandler):
        server_version = "financial-crime-skill-host"
        sys_version = ""

        def log_message(self, format, *args):  # never log bodies or identifiers
            pass

        def _send(self, status: int, payload: Any):
            data = json.dumps(payload).encode()
            self.send_response(status)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(data)))
            self.end_headers()
            self.wfile.write(data)

        def _error(self, status: int, code: str):
            self._send(status, {"error": {"code": code, "retryable": code in TRANSIENT, "detail_ref": None}})

        def do_GET(self):
            if self.path == "/healthz":
                return self._send(200, {"status": "ok", "bundle_digest": host.lock["bundle_digest"]})
            if not host.authorized(self.headers.get("Authorization")):
                return self._error(401, "ACCESS_DENIED")
            if self.path == "/v1/bundle":
                return self._send(200, host.lock)
            match = re.fullmatch(r"/v1/skills/executions/([^/]+)", self.path)
            if match:
                found = host.status(match.group(1))
                return self._send(200, found) if found else self._send(404, {})
            self._error(404, "INPUT_INVALID")

        def do_POST(self):
            if not host.authorized(self.headers.get("Authorization")):
                return self._error(401, "ACCESS_DENIED")
            cancel = re.fullmatch(r"/v1/skills/executions/([^/]+)/cancel", self.path)
            if cancel:
                found = host.status(cancel.group(1))
                # Executions run to completion before answering, so a known one is already terminal.
                return self._send(202, found) if found else self._send(404, {})
            match = re.fullmatch(r"/v1/skills/([^/]+)/executions", self.path)
            if not match or not SKILL_ID.match(match.group(1)):
                return self._error(404, "INPUT_INVALID")
            length = int(self.headers.get("Content-Length") or 0)
            if length > 4 * 1024 * 1024:
                return self._error(400, "INPUT_INVALID")
            try:
                body = json.loads(self.rfile.read(length) or b"null")
                response = host.execute(match.group(1), body, self.headers.get("Idempotency-Key"), self.headers.get("traceparent"))
            except json.JSONDecodeError:
                return self._error(400, "INPUT_INVALID")
            except HostError as error:
                return self._error(error.status, error.code)
            except (KeyError, TypeError, ValueError):
                return self._error(400, "INPUT_INVALID")
            self._send(200, response)

    return Handler


def main() -> None:
    try:
        verifier = CallerVerifier({GATEWAY_CALLER: "SKILL_HOST_AUTH_TOKEN"})
        outbound = OutboundToken("SKILL_HOST_GATEWAY_TOKEN")
    except WorkloadIdentityError as error:
        raise SystemExit(str(error)) from None
    host = SkillHost(verifier=verifier, gateway_token=outbound, envelopes=EnvelopeVerifier.from_env(),
                     executions=ExecutionStore(os.environ.get("SKILL_HOST_EXECUTIONS_DB") or None))
    port = int(os.environ.get("SKILL_HOST_PORT", "8090"))
    ThreadingHTTPServer((os.environ.get("SKILL_HOST_BIND", "0.0.0.0"), port), make_handler(host)).serve_forever()


if __name__ == "__main__":
    main()
